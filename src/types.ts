export interface OtpRecord {
  id: string;
  phone: string;      // E.164: +91XXXXXXXXXX
  code: string;       // 6-digit string
  expiresAt: string;  // ISO — 10 minutes from issue
  used: boolean;
}

export interface Session {
  id: string;
  userId: string;
  phone: string;
  userType: 'buyer' | 'seller';
  token: string;      // opaque to caller — generated by JwtPort
  issuedAt: string;
  expiresAt: string;  // ISO — 24 hours
  revoked: boolean;
}

export interface TokenPayload {
  sub: string;        // userId
  phone: string;
  userType: 'buyer' | 'seller';
  sessionId: string;
  iat: number;        // Unix seconds
  exp: number;        // Unix seconds
}
